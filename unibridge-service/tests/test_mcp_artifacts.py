def _workspace_file(body: bytes, name: str, mime: str = "image/png", **override) -> dict:
    """The object an MCP host puts where the model named a workspace file."""
    return {
        "filename": name,
        "mimeType": mime,
        "size": len(body),
        "sha256": _sha(body),
        "data": base64.b64encode(body).decode(),
        **override,
    }


