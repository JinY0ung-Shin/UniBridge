def _limits(**settings) -> mcp_artifacts.Limits:
    return mcp_artifacts.Limits.of(McpSettings(**settings))


def test_transfer_slots_are_shared_out():
    small = _limits(artifact_max_mb=1)
    assert (small.transfers, small.transfers_per_key) == (4, 2)
    slots = [mcp_artifacts.transfer_slot("a", small), mcp_artifacts.transfer_slot("a", small)]
    for slot in slots:
        slot.__enter__()
    try:
        # One key takes two at most...
        with pytest.raises(mcp_artifacts.ArtifactError) as refused:
            with mcp_artifacts.transfer_slot("a", small):
                pass
        assert refused.value.status_code == 429
        # ...and all keys four between them.
        with mcp_artifacts.transfer_slot("b", small), mcp_artifacts.transfer_slot("c", small):
            with pytest.raises(mcp_artifacts.ArtifactError):
                with mcp_artifacts.transfer_slot("d", small):
                    pass
    finally:
        for slot in slots:
            slot.__exit__(None, None, None)
    # A slot is given back even when the transfer fails.
    with pytest.raises(RuntimeError):
        with mcp_artifacts.transfer_slot("a", small):
            raise RuntimeError("transfer failed")
    assert mcp_artifacts._in_flight == {}


