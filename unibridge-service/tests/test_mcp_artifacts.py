class _Broken(httpx.AsyncByteStream):
    """A body that sends a little and then loses its connection."""

    async def __aiter__(self):
        yield b"\x89PNG"
        raise httpx.ReadError("connection reset")


async def test_download_never_stages_a_partial_or_failed_transfer(client, seeded_db, admin_token, gateway):
    headers = await _create_api_key(seeded_db, routes=EXT_KEY_ROUTES, databases=["store"])
    await _put_settings(client, admin_token, exposed_routes=[{"route_id": "orders"}], artifact_max_mb=1)
    api = {"source": "api", "api": "orders", "path": "/api/ext/orders/x"}

    async def refused(arguments: dict, message: str) -> None:
        result = await _call(client, headers, "download_artifact", arguments)
        assert result["isError"] is True, result
        assert message in _text(result)
        assert await _rows(seeded_db) == []

    with _routes():
        # Cut short: fewer bytes than announced.
        gateway.reply = httpx.Response(
            200, stream=httpx.ByteStream(BINARY[:100]), headers={"content-length": "2051"}
        )
        await refused(api, "cut short (100 of 2051 bytes)")
        # The connection broke mid-body.
        gateway.reply = httpx.Response(200, stream=_Broken())
        await refused(api, "interrupted")
        # Over the limit, announced: refused before the body is read...
        gateway.reply = httpx.Response(
            200, stream=_Broken(), headers={"content-length": str(MIB + 1)}
        )
        await refused(api, "Larger than one artifact may be (1 MiB)")
        # ...and unannounced: refused once the bytes pass it, never cut to fit.
        gateway.reply = httpx.Response(200, stream=httpx.ByteStream(b"\x00" * (MIB + 1)))
        await refused(api, "Larger than one artifact may be (1 MiB)")
        # An error answer is an error, not a file; its detail is passed on.
        gateway.reply = httpx.Response(404, json={"detail": "no such label"})
        await refused(api, "404: no such label")
        gateway.reply = httpx.Response(502, content=b"\x00" * 10_000)
        result = await _call(client, headers, "download_artifact", api)
        assert result["isError"] is True and len(_text(result)) < 600
        # A redirect is not the file and is not followed: its target is a URL
        # nobody offered. Neither is an answer without a body a file.
        gateway.reply = httpx.Response(
            302, content=b"<html>moved</html>", headers={"location": "https://elsewhere.example/f.bin", "content-type": "text/html"}
        )
        await refused(api, "302: the answer is a redirect, which is not followed")
        assert "elsewhere.example" not in _text(await _call(client, headers, "download_artifact", api))
        gateway.reply = httpx.Response(204)
        await refused(api, "204: the answer carries no whole file")
        gateway.reply = httpx.Response(206, content=BINARY[:10], headers={"content-range": "bytes 0-9/2051"})
        await refused(api, "206: the answer carries no whole file")
        assert [call for call in gateway.calls if call[1] != "GET"] == []

    # The S3 route's own answer says less than it should have sent.
    gateway.reply = None
    with _s3_file(BINARY[:10], announced=4000):
        await refused({"source": "s3", "connection": "store", "bucket": "b", "key": "k"}, "cut short")


# ── return_mode=resource: the file as a standard embedded resource ──────────


def _resource(result: dict) -> tuple[dict, dict, bytes]:
    """(metadata, the resource block's ``resource``, the decoded bytes)."""
    assert result["isError"] is False, result
    assert [item["type"] for item in result["content"]] == ["text", "resource"]
    resource = result["content"][1]["resource"]
    return json.loads(_text(result)), resource, base64.b64decode(resource["blob"], validate=True)


async def test_resource_mode_returns_a_standard_embedded_resource(client, seeded_db, gateway):
    headers = await _create_api_key(seeded_db, databases=["share"])
    with _nas_file(BINARY, filename="현장 사진 01.png", content_type="image/png") as open_stream:
        result = await _call(
            client,
            headers,
            "download_artifact",
            {"source": "nas", "connection": "share", "path": "lab/현장 사진 01.png", "return_mode": "resource"},
        )
    open_stream.assert_awaited_once_with("share", "lab/현장 사진 01.png", length=None)
    meta, resource, decoded = _resource(result)
    assert decoded == BINARY
    # MCP's own EmbeddedResource / BlobResourceContents, and nothing else in it:
    # not a file dict in structuredContent, no path, no artifact id.
    assert set(result) == {"content", "isError"}
    assert set(result["content"][1]) == {"type", "resource"}
    assert set(resource) == {"uri", "mimeType", "blob", "_meta"}
    assert resource["mimeType"] == "image/png"
    # What the host checks the decoded bytes against.
    assert resource["_meta"] == {"size": len(BINARY), "sha256": _sha(BINARY)}
    # The last URI segment is the file name, percent-encoded: a bare safe name.
    assert resource["uri"] == f"artifact://{_sha(BINARY)}/%ED%98%84%EC%9E%A5%20%EC%82%AC%EC%A7%84%2001.png"
    assert meta == {
        "filename": "현장 사진 01.png",
        "size": len(BINARY),
        "sha256": _sha(BINARY),
        "mime": "image/png",
        "return_mode": "resource",
    }
    # Read like a direct call, on nas-api; nothing is staged for this mode.
    assert gateway.calls == [("nas-api", "GET", "/api/nas/share/download")]
    assert await _rows(seeded_db) == []


