MIB = 1024 * 1024
# A small binary: every byte value, NULs included, nothing UTF-8 about it.
BINARY = bytes(range(256)) * 8 + b"\x00\xff\x00"
ARTIFACTS = "/mcp/artifacts"


def _sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _payload(result: dict) -> dict:
    assert result["isError"] is False, result
    return json.loads(_text(result))


@contextmanager
def _s3_file(body: bytes, content_type: str = "image/png", announced: int | None = None):
    """An S3 object behind /s3/<alias>/objects/download (the whole-object path)."""
    size = len(body) if announced is None else announced
    with patch("app.routers.s3.s3_manager.has_connection", return_value=True), patch(
        "app.routers.s3.s3_manager.allowed_buckets", return_value=None
    ), patch(
        "app.routers.s3.s3_manager.get_object_metadata",
        new_callable=AsyncMock,
        return_value={"size": size, "content_type": content_type},
    ), patch(
        "app.routers.s3.s3_manager.get_object",
        new_callable=AsyncMock,
        side_effect=lambda *args: {
            "Body": io.BytesIO(body),
            "ContentType": content_type,
            "ContentLength": size,
        },
    ) as get_object:
        yield get_object


@contextmanager
def _nas_file(body: bytes, filename: str = "scan.bin", content_type: str = "application/octet-stream"):
    async def chunks():
        yield body[: len(body) // 2]
        yield body[len(body) // 2 :]

    with patch("app.routers.nas.nas_manager.has_connection", return_value=True), patch(
        "app.routers.nas.nas_manager.open_read_stream",
        new_callable=AsyncMock,
        side_effect=lambda *args, **kwargs: (
            chunks(),
            {"size": len(body), "content_type": content_type, "filename": filename},
        ),
    ) as open_stream:
        yield open_stream


async def _rows(seeded_db) -> list[McpArtifact]:
    factory = async_sessionmaker(seeded_db, class_=AsyncSession, expire_on_commit=False)
    async with factory() as db:
        return list((await db.execute(select(McpArtifact).order_by(McpArtifact.created_at))).scalars())


async def _stage(client, headers, body: bytes, name: str = "notes.bin", content_type: str = "application/pdf", **extra):
    return await client.post(
        ARTIFACTS,
        content=body,
        headers={
            **headers,
            "Content-Type": content_type,
            "X-Artifact-Filename": quote(name),
            "X-Artifact-Sha256": _sha(body),
            **extra,
        },
    )


async def _multipart(request: httpx.Request):
    """The form a multipart request carries, parsed the way a server would."""
    body = request.content

    async def receive():
        return {"type": "http.request", "body": body, "more_body": False}

    scope = {
        "type": "http",
        "method": "POST",
        "path": request.url.path,
        "query_string": b"",
        "headers": [(name.lower(), value) for name, value in request.headers.raw],
    }
    return await Request(scope, receive).form()


