    # One artifact's size: refused, never cut to fit.
    resp = await _stage(client, headers, b"\x01" * (MIB + 1))
    assert resp.status_code == 413 and "1 MiB" in resp.json()["detail"]

    # What one key may hold...
    assert (await _stage(client, headers, b"\x01" * MIB, name="a")).status_code == 201
    assert (await _stage(client, headers, b"\x02" * MIB, name="b")).status_code == 201
    resp = await _stage(client, headers, b"\x03" * 1024, name="c")
    assert resp.status_code == 429 and "already holds" in resp.json()["detail"]
    # ...and what all keys hold together.
    assert (await _stage(client, other, b"\x04" * MIB, name="d")).status_code == 201
    resp = await _stage(client, other, b"\x05" * 1024, name="e")
    assert resp.status_code == 503 and "full" in resp.json()["detail"]
    assert len(await _rows(seeded_db)) == 3

    # Deleting makes room again.
    held = (await _rows(seeded_db))[0]
    assert (await client.delete(f"{ARTIFACTS}/{held.id}", headers=headers)).status_code == 204
    assert (await _stage(client, other, b"\x05" * 1024, name="e")).status_code == 201


